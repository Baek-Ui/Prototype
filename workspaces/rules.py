    + _ACCT_NO_DEMAND + "|" + _REMIT_VERB + "|보내주|돈을 보내|돈 좀 보내|돈이 필요|"
    + "신분증 사본|신분증 사진|" + _ID_DEMAND + "|" + _PW_DEMAND
    + "))"
